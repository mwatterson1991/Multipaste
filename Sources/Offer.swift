import AppKit

/// One copy placed on the clipboard as a promise: its formats are listed, but the contents are handed over only when asked for.
/// macOS asks at the moment something pastes. That is how the app knows a paste happened without watching the keyboard,
/// which is what would need the Accessibility permission.
final class Offer: NSObject, NSPasteboardItemDataProvider {
    /// Present on everything this app puts on the clipboard, so the watcher never counts it as a new copy.
    static let marker = NSPasteboard.PasteboardType("io.github.mwatterson1991.multipaste.offer")

    // Clipboard history tools leave anything carrying these alone. Without them a history tool would read the
    // promise the instant it appeared, and that read is indistinguishable from a paste.
    private static let historyOptOut = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    // The clipboard does not promise to keep its provider alive, and it can still ask after the app has moved on.
    private static var live: Set<Offer> = []

    /// Runs each time the contents are asked for. One paste can ask several times, once per format.
    var onTaken: (() -> Void)?

    private let clip: Clip
    private var items: [NSPasteboardItem] = []

    init(clip: Clip) {
        self.clip = clip
    }

    func write(to pasteboard: NSPasteboard) {
        items = clip.items.map { reps in
            let item = NSPasteboardItem()
            _ = item.setDataProvider(self, forTypes: reps.map { $0.type })
            return item
        }
        if let first = items.first {
            let present = Data("1".utf8)
            _ = first.setData(present, forType: Offer.marker)
            for type in Offer.historyOptOut {
                _ = first.setData(present, forType: type)
            }
        }
        Offer.live.insert(self)
        pasteboard.clearContents()
        _ = pasteboard.writeObjects(items)
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        var reps: [Clip.Rep] = []
        if let position = items.firstIndex(where: { $0 === item }) {
            reps = clip.items[position]
        } else if let match = clip.items.first(where: { $0.contains(where: { $0.type == type }) }) {
            reps = match
        }
        if let rep = reps.first(where: { $0.type == type }) {
            _ = item.setData(rep.data, forType: type)
        }
        onTaken?()
    }

    func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {
        Offer.live.remove(self)
    }
}
