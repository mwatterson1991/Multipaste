import AppKit

/// One copy: everything that was on the pasteboard, in every format the source app offered.
struct Clip: Equatable {
    struct Rep: Equatable {
        let type: NSPasteboard.PasteboardType
        let data: Data
    }

    enum Kind {
        case text, image, files, other
    }

    struct ImageFile {
        let data: Data
        let fileExtension: String
    }

    let items: [[Rep]]
    let kind: Kind

    // Password managers tag what they copy with these so clipboard tools leave it alone.
    private static let privateMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private static let png = NSPasteboard.PasteboardType.png
    private static let tiff = NSPasteboard.PasteboardType.tiff
    private static let jpeg = NSPasteboard.PasteboardType("public.jpeg")
    private static let gif = NSPasteboard.PasteboardType("com.compuserve.gif")
    private static let heic = NSPasteboard.PasteboardType("public.heic")
    private static let webp = NSPasteboard.PasteboardType("org.webmproject.webp")
    private static let webAddress = NSPasteboard.PasteboardType("public.url")
    private static let imageTypes: Set<NSPasteboard.PasteboardType> = [png, tiff, jpeg, gif, heic, webp]

    enum Capture {
        case clip(Clip)
        /// The source app marked the copy as private.
        case secret
        /// Nothing readable is there: the clipboard was emptied, or an app has announced a copy and not supplied it yet.
        case nothing
    }

    static func capture(from pasteboard: NSPasteboard) -> Capture {
        guard let pasteboardItems = pasteboard.pasteboardItems else { return .nothing }
        var items: [[Rep]] = []
        for item in pasteboardItems {
            if item.types.contains(where: { privateMarkers.contains($0.rawValue) }) { return .secret }
            let reps = item.types.compactMap { type -> Rep? in
                guard let data = item.data(forType: type) else { return nil }
                return Rep(type: type, data: data)
            }
            if !reps.isEmpty { items.append(reps) }
        }
        guard !items.isEmpty else { return .nothing }
        return .clip(Clip(items: items, kind: classify(items)))
    }

    private static func classify(_ items: [[Rep]]) -> Kind {
        let reps = items.flatMap { $0 }
        let types = Set(reps.map { $0.type })
        if types.contains(NSPasteboard.PasteboardType.fileURL) { return .files }

        let string = reps.first(where: { $0.type == NSPasteboard.PasteboardType.string })
            .flatMap { String(data: $0.data, encoding: .utf8) }

        if !types.isDisjoint(with: imageTypes) {
            // A spreadsheet also copies a picture of its cells, and that should stay text.
            // An image from a web page carries no text beyond its own address.
            guard let string = string else { return .image }
            if types.contains(webAddress) || isWebAddress(string) { return .image }
        }

        guard string != nil else { return .other }

        // Layers copied in Figma travel inside the HTML, so joining them as plain text would lose the layers.
        if let html = reps.first(where: { $0.type == NSPasteboard.PasteboardType.html }),
           let markup = String(data: html.data, encoding: .utf8),
           markup.contains("(figmeta)") {
            return .other
        }
        return .text
    }

    private static func isWebAddress(_ string: String) -> Bool {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        let oneWord = !trimmed.contains(" ") && !trimmed.contains("\n")
        return oneWord && (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://"))
    }

    var text: String? {
        for reps in items {
            if let rep = reps.first(where: { $0.type == NSPasteboard.PasteboardType.string }) {
                return String(data: rep.data, encoding: .utf8)
            }
        }
        return nil
    }

    var fileURLs: [URL] {
        items.compactMap { reps -> URL? in
            guard let rep = reps.first(where: { $0.type == NSPasteboard.PasteboardType.fileURL }),
                  let url = URL(dataRepresentation: rep.data, relativeTo: nil) else { return nil }
            return (url as NSURL).filePathURL ?? url
        }
    }

    /// The image as a file a design tool accepts. Original bytes are kept when they are already PNG, JPEG or GIF.
    var imageFile: ImageFile? {
        let reps = items.flatMap { $0 }
        if let rep = reps.first(where: { $0.type == Clip.png }) {
            return ImageFile(data: rep.data, fileExtension: "png")
        }
        if let rep = reps.first(where: { $0.type == Clip.jpeg }) {
            return ImageFile(data: rep.data, fileExtension: "jpg")
        }
        if let rep = reps.first(where: { $0.type == Clip.gif }) {
            return ImageFile(data: rep.data, fileExtension: "gif")
        }
        for rep in reps where Clip.imageTypes.contains(rep.type) {
            if let bitmap = NSBitmapImageRep(data: rep.data),
               let converted = bitmap.representation(using: .png, properties: [:]) {
                return ImageFile(data: converted, fileExtension: "png")
            }
        }
        return nil
    }

    /// Puts this copy back on the pasteboard exactly as it was captured.
    func write(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let pasteboardItems = items.map { reps -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for rep in reps {
                _ = item.setData(rep.data, forType: rep.type)
            }
            return item
        }
        _ = pasteboard.writeObjects(pasteboardItems)
    }
}
